#!/usr/bin/env python3
"""PRD 4 layer E: the forge's recipes. The shops keep their own buying screen, but intermediate and top equipment asks
for Hunt Materials as well as Bits (the owner's economy: commons in large amounts, rares for the best gear; the Black
Market will turn rares into commons).

  tools/venv/bin/python tools/gen_recipes.py            # write port/game/definitive_recipes.c and the list for review
  tools/venv/bin/python tools/gen_recipes.py --check    # exit 1 if the committed table is not the rule's

Reads the items from src/main/records.c, the shops' goods from src/stitshop/stitshop_800859C0.c, the rare items from
port/game/definitive_hunt_targets.c and the commons' names from tools/text_override/en.txt; the rare items' names in
the list need the user's disc (gen_enemy_weaknesses.species), the table does not. The numbers are definitive.h's
(DEF_RECIPE_*). Rule, on the old buying price (before layer D's drain), for the weapons, armour and accessories a shop
sells:
  - under DEF_RECIPE_FROM: Bits only (the start of the game stays as it was);
  - intermediate, up to DEF_RECIPE_TOP: one common material, the 3rd to the 9th by price rank, DEF_RECIPE_MID_LO to
    DEF_RECIPE_MID_HI of it, rising with the price;
  - top: one of the last seven commons, DEF_RECIPE_TOP_LO to DEF_RECIPE_TOP_HI of it, and a rare item: the rares in the
    order of their target's level, spread over the top items by price, one (two from DEF_RECIPE_TWO_RARES).
Quantities are rounded to 5; ties by item ID.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
GEN = ROOT / "port/game/definitive_recipes.c"
OUT = ROOT / ".dumps/tasks/forge"
EQUIP = {"RECORDS_ITEM_WEAPON", "RECORDS_ITEM_ARMOR", "RECORDS_ITEM_ACCESSORY"}
ROMAN = ["", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"]


def constants():
    h = (ROOT / "port/game/definitive.h").read_text()
    c = {k: int(v, 0) for k, v in re.findall(r"#define (DEF_RECIPE_\w+)\s+(\w+)", h)}
    for k in ("DEF_RECIPE_FROM", "DEF_RECIPE_TOP", "DEF_RECIPE_MID_LO", "DEF_RECIPE_MID_HI", "DEF_RECIPE_TOP_LO",
              "DEF_RECIPE_TOP_HI", "DEF_RECIPE_TWO_RARES"):
        assert k in c, k
    return c


def items():
    s = (ROOT / "src/main/records.c").read_text()
    body = s[s.index("RecordsItem records_items[] = {"):]
    body = body[:body.index("\n};")]
    return {int(m.group(6)): dict(price=int(m.group(2)), cat=m.group(4), name=m.group(7))
            for m in re.finditer(r"\{ (\S+), (\d+), (\d+), (\w+), (\d+), \{ 0, 0 \} \}, /\* (\d+) (.*?) \*/", body)}


def sold():
    s = (ROOT / "src/stitshop/stitshop_800859C0.c").read_text()
    out = set()
    for _n, body in re.findall(r"s16 stitshop_goods_(\d+)\[\] = \{(.*?)\};", s, re.S):
        out |= {int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body) if int(x, 0)}
    return out


def rares():
    """[(level, index, battle, variant)] of def_hunt_targets, in table order (the index is the rare item's)."""
    s = (ROOT / "port/game/definitive_hunt_targets.c").read_text()
    rows = re.findall(r"\{ 0x([0-9A-F]+), (\d+), (\d+), (\d+) \}", s)
    return [(int(lv), i, int(b), int(v)) for i, (_r, b, lv, v) in enumerate(rows)]


def r5(v):
    return max(5, (v + 2) // 5 * 5)


def spread(rank, n, lo, hi):
    return lo if n <= 1 else lo + (hi - lo) * rank // (n - 1)


def table():
    c, its, shop = constants(), items(), sold()
    cand = sorted(((it["price"], i) for i, it in its.items() if it["cat"] in EQUIP and i in shop
                   and it["price"] >= c["DEF_RECIPE_FROM"]))
    mid = [i for p, i in cand if p < c["DEF_RECIPE_TOP"]]
    top = [i for p, i in cand if p >= c["DEF_RECIPE_TOP"]]
    order = [i for _lv, i, _b, _v in sorted(rares())]
    rows = {}
    for rank, i in enumerate(mid):
        rows[i] = (spread(rank, len(mid), 2, 8), r5(spread(rank, len(mid), c["DEF_RECIPE_MID_LO"], c["DEF_RECIPE_MID_HI"])),
                   -1, 0)
    for rank, i in enumerate(top):
        rare = order[rank * len(order) // len(top)]
        rows[i] = (spread(rank, len(top), 9, 15), r5(spread(rank, len(top), c["DEF_RECIPE_TOP_LO"], c["DEF_RECIPE_TOP_HI"])),
                   rare, 2 if its[i]["price"] >= c["DEF_RECIPE_TWO_RARES"] else 1)
    return [(i, its[i]) + rows[i] for i in sorted(rows)]


def render(rows):
    lines = ["/* Generated by tools/gen_recipes.py (PRD 4 layer E): the forge's recipes, by item ID: a common Hunt Material and",
             " * how many, then a rare item (its index in def_hunt_targets, -1: none) and how many. Regenerate instead of",
             " * editing. */", '#include "definitive.h"', "", "const DefRecipe def_recipes[] = {"]
    for i, it, com, n, rare, rn in rows:
        lines.append(f"    {{ {i}, {com}, {n}, {rare}, {rn} }}, /* {it['name']} ({it['price']}) */")
    lines += ["};", f"const int def_recipe_count = {len(rows)};", ""]
    return "\n".join(lines)


def write_md(rows):
    OUT.mkdir(parents=True, exist_ok=True)
    en = (ROOT / "tools/text_override/en.txt").read_text()
    mats = {int(i): n.strip() for i, n in re.findall(r"^\$HuntMat(\d+): (.*)$", en, re.M)}
    try:
        import gen_enemy_weaknesses as gw
        import gen_hunt_targets as gh
        names = {sp["id"]: sp["name"] for sp in gw.species()}
        battles = gh.battle_info()
        rare_name = {i: f"{names.get(battles[b]['enemies'][0][0], '?')} Core "
                        f"{'X' * (v // 10) + ROMAN[v % 10]}" for _lv, i, b, v in rares()}
    except Exception as e:  # no disc here: the rares by index
        print("rare names unavailable:", e)
        rare_name = {}
    c = constants()
    lines = ["# Receitas da forja (PRD 4 camada E), aplicadas", "",
             f"Equipamento vendido em loja a partir de {c['DEF_RECIPE_FROM']} Bits (preço antigo) pede material além dos Bits; "
             f"até {c['DEF_RECIPE_TOP']} um comum, daí em diante um comum em grande quantidade e um raro de região.", "",
             "| ID | item | preço antigo | comum | raro |", "| --- | --- | --- | --- | --- |"]
    for i, it, com, n, rare, rn in rows:
        r = "—" if rare < 0 else f"{rare_name.get(rare, f'raro {rare}')} x{rn}"
        lines.append(f"| {i} | {it['name']} | {it['price']} | {mats.get(com, com)} x{n} | {r} |")
    (OUT / "receitas.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = table()
    text = render(rows)
    if a.check:
        ok = GEN.exists() and GEN.read_text() == text
        sane = all(0 <= com < 16 and 0 < n <= 99 and (rare == -1) == (rn == 0) for _i, _it, com, n, rare, rn in rows)
        print(f"{'ok' if ok else 'FAIL'} the recipes are the rule's ({len(rows)} items); {'ok' if sane else 'FAIL'} "
              "materials and counts in range")
        return 0 if ok and sane else 1
    GEN.write_text(text)
    write_md(rows)
    print(f"{GEN.relative_to(ROOT)}: {len(rows)} recipes; {OUT / 'receitas.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
