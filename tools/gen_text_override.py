#!/usr/bin/env python3
"""Encode the port's text overrides (definitive combat PRD, layer 1) into port/game/definitive_text.c.

  tools/venv/bin/python tools/gen_text_override.py            # write port/game/definitive_text.c
  tools/venv/bin/python tools/gen_text_override.py --check    # exit 1 if the committed file is stale

Source: tools/text_override/en.txt, one line per entry, `FILE index: text` (FILE is the text file's name without the
language prefix, e.g. SKLINF; index is the table entry; `#` starts a comment). A line `$NAME: text` is not an
override: it is a string of the port's own (the battle HUD's labels), exported as `def_str_NAME` (a glyph-byte array). The text is plain ASCII; the game's glyph
codes are looked up in the user's EXE (tools/dump_text.py char_tables), so no disc data is embedded: only our own
words, as glyph bytes. The overrides apply to the English text sets (records_language 1 and 2) and replace the entry
at run time (port/game/definitive.c, def_text_override, called by font_get_entry); other languages are untouched.
The encoding is checked by round trip against the disc's own entries before anything is written.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import disc_files as df  # noqa: E402
import dump_text as dt  # noqa: E402

SRC = ROOT / "tools/text_override/en.txt"
OUT = ROOT / "port/game/definitive_text.c"
ALIAS = {"-": "−", "'": "’"}  # the font draws a minus sign and a curly apostrophe


def inverse(tables):
    """char -> its bytes: a main glyph is one byte, an extra glyph (space, punctuation) is `01 xx`."""
    chars, ext = tables
    inv = {}
    for g, code in sorted(chars.items()):
        inv.setdefault(dt.sjis(code), bytes([g]))
    for g, code in sorted(ext.items()):
        inv.setdefault(dt.sjis(code), bytes([1, g]))
    return inv


CONTROL = re.compile(r"<(\d+(?:,\d+)*)>")


def encode(text, inv):
    """ASCII plus the game's control codes in dump_text's notation: `<5,1>` is bytes 02 05 01 (code 5, argument 1), `<1>` a
    line break (02 01). The length of each code is checked against message_code_lengths."""
    out = bytearray()
    i = 0
    while i < len(text):
        m = CONTROL.match(text, i)
        if m:
            nums = [int(x) for x in m.group(1).split(",")]
            want = dt.CODE_LENGTHS[nums[0]] if nums[0] < len(dt.CODE_LENGTHS) and dt.CODE_LENGTHS[nums[0]] >= 2 else 2
            if len(nums) + 1 != want:
                sys.exit(f"{SRC.name}: control code <{m.group(1)}> must have {want - 2} argument(s): {text!r}")
            out += bytes([2] + nums)
            i = m.end()
            continue
        ch = ALIAS.get(text[i], text[i])
        if ch not in inv:
            sys.exit(f"{SRC.name}: no glyph for {ch!r} in {text!r}")
        out += inv[ch]
        i += 1
    return bytes(out)


def jpn_id(name):
    """The Japanese file's ID (the base records_language is added to) of text file `name`."""
    e = dt.find_file(name, "JPN")
    return e.id


def load_source():
    rows = []
    for n, line in enumerate(SRC.read_text().splitlines(), 1):
        line = line.split("#", 1)[0].rstrip() if not line.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        head, sep, text = line.partition(":")
        parts = head.split()
        if sep and len(parts) == 1 and parts[0].startswith("$"):
            rows.append((parts[0], -1, text.strip()))
            continue
        if not sep or len(parts) != 2 or not parts[1].isdigit():
            sys.exit(f"{SRC.name}:{n}: expected `FILE index: text`")
        rows.append((parts[0].upper(), int(parts[1]), text.strip()))
    return rows


def roundtrip(tables, inv):
    """Every entry of the disc's ENG text files named below that is plain glyphs and control codes re-encodes to the same
    bytes (the encoder is checked against the game's own text before anything is written)."""
    bad = 0
    for name in ("SKLINF", "SKLNAM", "STATUS", "TRAINI"):
        d = (df.DISC / dt.find_file(name, "ENG").path).read_bytes()
        (_, offs), = dt.tables_of(d)
        for o in offs:
            raw = d[o:d.index(0, o)]
            text, b = dt.decode(d, o, tables, latin=False)
            text = text.replace("\n    ", "").replace("\u2212", "-").replace("\u2019", "'")
            if b == 0 and all(ord(c) < 128 for c in text.replace("\u2192", "")):
                try:
                    if encode(text, inv) != raw:
                        bad += 1
                except SystemExit:
                    bad += 1
    return bad


def render(rows, tables, inv):
    lines = ["/* Generated by tools/gen_text_override.py from tools/text_override/en.txt: do not edit. */",
             '#include "definitive.h"', ""]
    over = [r for r in rows if not r[0].startswith("$")]
    for i, (name, idx, text) in enumerate(rows):
        b = encode(text, inv) + b"\0"
        sym = f"def_str_{name[1:]}" if name.startswith("$") else f"def_text_{i}"
        lines.append(f"{'' if name.startswith('$') else 'static '}const unsigned char {sym}[] = {{ "
                     + ", ".join(f"0x{x:02X}" for x in b) + " };" + (f" /* {text} */" if name.startswith("$") else ""))
    lines += ["", "const DefTextOverride def_text_overrides[] = {"]
    for i, (name, idx, text) in enumerate(rows):
        if not name.startswith("$"):
            lines.append(f"    {{ 0x{jpn_id(name):X}, {idx}, def_text_{i} }}, /* {name} {idx}: {text} */")
    lines += ["};", f"const int def_text_override_count = {len(over)};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    tables = dt.char_tables()
    inv = inverse(tables)
    bad = roundtrip(tables, inv)
    if bad:
        sys.exit(f"the encoder does not reproduce {bad} entries of the disc's text: the glyph table is wrong")
    text = render(load_source(), tables, inv)
    if a.check:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {text.count('def_text_overrides')} table, entries from {SRC.name}")


if __name__ == "__main__":
    main()
