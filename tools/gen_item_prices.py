#!/usr/bin/env python3
"""PRD 4 layer D: the definitive prices. Advanced equipment a shop sells costs more, so OVERFINISH's Bits have somewhere
to go, and resells for much less, so a top weapon found, won or bought cheap no longer sells for 30000.

  tools/venv/bin/python tools/gen_item_prices.py            # write port/game/definitive_prices.c and the list for review
  tools/venv/bin/python tools/gen_item_prices.py --check    # exit 1 if the committed table is not the rule's

Reads the items from src/main/records.c (records_items: buying and selling price, category, the English name in the
comment) and the shops' goods from src/stitshop/stitshop_800859C0.c (stitshop_goods_N); no disc. The rule's numbers
are definitive.h's (DEF_PRICE_*, DEF_SELL_*). Rule: a weapon, armour or accessory a shop sells whose buying price is at
least DEF_PRICE_KNEE costs DEF_PRICE_DRAIN_PCT of it, and sells for DEF_SELL_BASE plus DEF_SELL_ABOVE_PCT of what its old
price had above the knee (the owner's example: a 60000 sword that sold for 30000 sells for 9000), never more than half
its new price; both rounded to 100. Everything else keeps the game's prices (half the price on resale, as the game
has it). The game applies the table through def_item_buy / def_item_sell (port/game/definitive_economy.c).
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "port/game/definitive_prices.c"
OUT = ROOT / ".dumps/tasks/prices"
EQUIP = {"RECORDS_ITEM_WEAPON", "RECORDS_ITEM_ARMOR", "RECORDS_ITEM_ACCESSORY"}


def constants():
    h = (ROOT / "port/game/definitive.h").read_text()
    c = {k: int(v, 0) for k, v in re.findall(r"#define (DEF_PRICE_\w+|DEF_SELL_\w+)\s+(\w+)", h)}
    for k in ("DEF_PRICE_KNEE", "DEF_PRICE_DRAIN_PCT", "DEF_SELL_BASE", "DEF_SELL_ABOVE_PCT"):
        assert k in c, k
    return c


def items():
    s = (ROOT / "src/main/records.c").read_text()
    body = s[s.index("RecordsItem records_items[] = {"):]
    body = body[:body.index("\n};")]
    out = {}
    for m in re.finditer(r"\{ (\S+), (\d+), (\d+), (\w+), (\d+), \{ 0, 0 \} \}, /\* (\d+) (.*?) \*/", body):
        out[int(m.group(6))] = dict(price=int(m.group(2)), sell=int(m.group(3)), cat=m.group(4), type=int(m.group(5)),
                                    name=m.group(7))
    return out


def shops():
    s = (ROOT / "src/stitshop/stitshop_800859C0.c").read_text()
    sold_in = defaultdict(list)
    for n, body in re.findall(r"s16 stitshop_goods_(\d+)\[\] = \{(.*?)\};", s, re.S):
        for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body):
            if int(x, 0):
                sold_in[int(x, 0)].append(int(n))
    return sold_in


def r100(v):
    return (v + 50) // 100 * 100


def rule(it, where, c):
    """(buy, sell) for an item the rule changes, else None."""
    if it["cat"] not in EQUIP or not where or it["price"] < c["DEF_PRICE_KNEE"]:
        return None
    buy = r100(it["price"] * c["DEF_PRICE_DRAIN_PCT"] // 100)
    sell = r100(c["DEF_SELL_BASE"] + (it["price"] - c["DEF_PRICE_KNEE"]) * c["DEF_SELL_ABOVE_PCT"] // 100)
    return buy, min(sell, buy // 2)


def table():
    c, its, where = constants(), items(), shops()
    rows = []
    for i in sorted(its):
        r = rule(its[i], where.get(i), c)
        if r is not None:
            rows.append((i, its[i], where[i], r))
    return rows, its, where


def render(rows):
    lines = ["/* Generated by tools/gen_item_prices.py (PRD 4 layer D): the items whose prices the definitive rule changes,",
             " * by item ID; every other item keeps records_items'. Regenerate instead of editing. */",
             '#include "definitive.h"', "", "const DefItemPrice def_item_prices[] = {"]
    for i, it, _w, (buy, sell) in rows:
        lines.append(f"    {{ {i}, {buy}, {sell} }}, /* {it['name']}: {it['price']} / {it['sell']} */")
    lines += ["};", f"const int def_item_price_count = {len(rows)};", ""]
    return "\n".join(lines)


def write_md(rows, its, where):
    OUT.mkdir(parents=True, exist_ok=True)
    c = constants()
    lines = ["# Preços definitivos (PRD 4 camada D), aplicados", "",
             f"Regra: arma, armadura ou acessório vendido em loja com preço de compra a partir de {c['DEF_PRICE_KNEE']} custa "
             f"{c['DEF_PRICE_DRAIN_PCT']}% e revende por {c['DEF_SELL_BASE']} + {c['DEF_SELL_ABOVE_PCT']}% do que o preço antigo "
             "passava disso (nunca mais que metade do novo), arredondado a 100. O resto fica como no jogo (revenda = metade).",
             "", "| ID | item | lojas | compra | venda | compra nova | venda nova |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for i, it, w, (buy, sell) in rows:
        lines.append(f"| {i} | {it['name']} | {' '.join(map(str, sorted(set(w))))} | {it['price']} | {it['sell']} | {buy} | {sell} |")
    found = [(i, it) for i, it in its.items() if it["cat"] in EQUIP and i not in where and it["sell"]]
    lines += ["", f"Equipamentos que nenhuma loja vende (achados, prêmios): {len(found)}, revenda até "
              f"{max(it['sell'] for _, it in found)}, sem mudança."]
    (OUT / "precos.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows, its, where = table()
    text = render(rows)
    if a.check:
        ok = GEN.exists() and GEN.read_text() == text
        buys = [r[3] for r in sorted(rows, key=lambda r: r[1]["price"])]
        mono = all(x[0] <= y[0] and x[1] <= y[1] for x, y in zip(buys, buys[1:]))
        print(f"{'ok' if ok else 'FAIL'} the table is the rule's ({len(rows)} items); {'ok' if mono else 'FAIL'} "
              "dearer items never resell for less")
        return 0 if ok and mono else 1
    GEN.write_text(text)
    write_md(rows, its, where)
    print(f"{GEN.relative_to(ROOT)}: {len(rows)} items; {OUT / 'precos.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
